/**
 * Builds the tool list a given bot is ALLOWED to call, from its evidence-gated
 * capabilities (see ingest.js::deriveCapabilities). A bot with
 * capabilities.checkout.enabled === false literally has no checkout tool to
 * call -- this is what makes the till-number-fabrication bug structurally
 * impossible rather than something an intent-engine regex has to catch.
 *
 * @param {import('./ingest.js').Capabilities} capabilities
 * @param {object} deps  { store, botId, siteOrigin, paymentProvider, embedFn }
 */
export function getToolsForBot(capabilities, deps = {}) {
  const tools = [];
  const caps = (capabilities && capabilities.capabilities) ? capabilities.capabilities : (capabilities || {});

  const canSearchCatalog = !!(caps.catalogBrowsing?.enabled ?? caps.catalogBrowsing ?? caps.catalog_search);
  if (canSearchCatalog) {
    tools.push({
      name: 'search_products',
      description: 'Search this business\'s own product catalog by name or category. Use whenever the user names an item or shopping need, in whatever words they use.',
      parameters: { query: 'string', category_hint: 'string, optional' },
      run: async ({ query }) => {
        const embedFn = deps.embedFn || defaultEmbedFn;
        const qEmbedding = await Promise.resolve(embedFn([query])).then(r => r[0]);
        const results = deps.store.search(deps.botId, qEmbedding, {
          contentTypeFilter: ['product'],
          topK: 5,
        }).filter(r => r.score >= RELEVANCE_THRESHOLD);
        return results.map(r => ({
          name: r.chunk.pageTitle,
          url: r.chunk.pageUrl,
          price: r.chunk.structuredData?.price ?? null,
          currency: r.chunk.structuredData?.currency ?? null,
          inStock: r.chunk.structuredData?.inStock ?? null,
          score: r.score,
        }));
      },
    });
  }

  const canBook = !!(caps.appointmentBooking?.enabled ?? caps.appointmentBooking ?? caps.booking);
  if (canBook) {
    tools.push({
      name: 'check_availability',
      description: 'Check open appointment/consultation slots for this business.',
      parameters: { preferred_date: 'string, optional' },
      run: async () => deps.bookingProvider ? deps.bookingProvider.getSlots() : { slots: [], note: 'Booking system not connected yet -- escalate to the team.' },
    });
  }

  const canLeadCapture = (caps.leadCapture?.enabled ?? caps.leadCapture ?? caps.lead_capture) !== false;
  if (canLeadCapture) {
    tools.push({
      name: 'capture_lead',
      description: 'Record customer contact info for human team follow up.',
      parameters: { name: 'string', phone: 'string', email: 'string, optional', note: 'string, optional' },
      run: async (lead) => ({ ok: true, lead })
    });
  }

  // No `if (capabilities.checkout.enabled)` branch. Checkout is handled
  // exclusively by buildCheckoutInstructions() below, gated on a verified
  // payment credential, never on a capability flag alone.

  return tools;
}

