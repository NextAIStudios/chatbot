/**
 * Refuses unless the business has an explicitly verified payment credential
 * on file (set only through a human-confirmed owner flow, never inferred
 * from crawled/scraped content). This is what the M-Pesa till-number bug
 * needs: one gate, one place, impossible to route around from a chat reply.
 *
 * @param {object} bot
 * @param {{name:string, price:number, currency:string}} item
 * @returns {{ok:true, type:string, instructions:string, till?:string, paybill?:string, businessName?:string} | {ok:false, reason:string}}
 */
export function buildCheckoutInstructions(bot, item = {}) {
  const cred = bot?.verifiedPaymentCredential || bot?.checkout?.verifiedPaymentCredential;
  if (!cred || !cred.verifiedAt) {
    return { ok: false, reason: 'no_verified_payment_credential' };
  }

  const businessName = cred.businessName || bot?.company?.name || '';
  const currency = item.currency || 'KES';
  const priceFormatted = Number(item.price || 0).toLocaleString();

  if (cred.type === 'mpesa_till' || cred.type === 'buy_goods') {
    const till = cred.till || cred.number || cred.tillNumber;
    if (!till) return { ok: false, reason: 'missing_till_number' };
    return {
      ok: true,
      type: 'buy_goods',
      till: String(till),
      businessName,
      instructions:
        `1. Go to M-Pesa on your phone and select Lipa na M-Pesa\n` +
        `2. Select Buy Goods and Services\n` +
        `3. Enter Till Number: ${till}${businessName ? ' (' + businessName + ')' : ''}\n` +
        `4. Enter Amount: ${currency} ${priceFormatted}\n` +
        `5. Enter your M-Pesa PIN and send`,
    };
  }

  if (cred.type === 'paybill') {
    const paybill = cred.paybill || cred.number || cred.paybillNumber;
    if (!paybill) return { ok: false, reason: 'missing_paybill_number' };
    const account = cred.account || item.name || 'ORDER';
    return {
      ok: true,
      type: 'paybill',
      paybill: String(paybill),
      account: String(account),
      businessName,
      instructions:
        `1. Go to M-Pesa on your phone and select Lipa na M-Pesa\n` +
        `2. Select Pay Bill\n` +
        `3. Enter Business Number: ${paybill}${businessName ? ' (' + businessName + ')' : ''}\n` +
        `4. Enter Account Number: ${account}\n` +
        `5. Enter Amount: ${currency} ${priceFormatted}\n` +
        `6. Enter your M-Pesa PIN and send`,
    };
  }

  return { ok: false, reason: `unsupported_credential_type_${cred.type}` };
}

// ---------------------------------------------------------------------------
// Answering a query
// ---------------------------------------------------------------------------

/**
 * @param {object} params
 * @param {string} [params.botId='default']
 * @param {object} params.bot            Full bot config: { capabilities, company, verifiedPaymentCredential, ... }
 * @param {string} params.message        Raw user message
 * @param {KnowledgeStore} params.store
 * @param {(texts:string[]) => Promise<number[][]>} [params.embedFn=defaultEmbedFn]
 * @param {(args:{message:string, chunks:object[], toolResults:object[]}) => Promise<string>} [params.composeFn=defaultComposeFn]
 *        LLM call that composes prose from retrieved facts/tool results.
 *        The prompt passed to it MUST instruct: answer only from the given
 *        chunks/tool results; if insufficient, say so; never state a price,
 *        stock status, or payment instruction that isn't in the provided data.
 */
export async function answerQuery({
  botId = 'default',
  bot = {},
  message = '',
  store,
  embedFn = defaultEmbedFn,
  composeFn = defaultComposeFn,
}) {
  const tools = getToolsForBot(bot.capabilities, { store, botId, embedFn, bookingProvider: bot.bookingProvider });

  // 1. Retrieval, gated by the single relevance threshold.
  const queryEmbedding = await Promise.resolve(embedFn([message])).then(r => r[0]);
  const retrieved = store.search(botId, queryEmbedding, { topK: TOP_K, rawQuery: message });
  const grounded = retrieved.filter(r => r.score >= RELEVANCE_THRESHOLD);

  // 2. If this looks like a tool-shaped ask (product search, booking) try the
  //    tool regardless of retrieval score -- retrieval covers static content,
  //    tools cover anything that changes faster than the crawl.
  const toolResults = [];
  if (looksLikeProductQuery(message) && tools.some(t => t.name === 'search_products')) {
    const tool = tools.find(t => t.name === 'search_products');
    const results = await tool.run({ query: message });
    if (results.length) toolResults.push({ tool: 'search_products', results });
  }

  // 3. Nothing grounded and no tool hit -> honest fallback, never a guess.
  if (grounded.length === 0 && toolResults.length === 0) {
    return buildFallback({ bot, message, capabilities: bot.capabilities });
  }

  // 4. Compose from ONLY what was actually retrieved/returned. The model is
  //    never allowed to fill gaps from its own general knowledge, and is
  //    never handed the ability to emit payment instructions here --
  //    checkout only happens via buildCheckoutInstructions(), called
  //    separately once the user has picked a specific verified item.
  const reply = await composeFn({
    message,
    chunks: grounded.map(g => ({ text: g.chunk.text, url: g.chunk.pageUrl, score: g.score })),
    toolResults,
  });

  return {
    reply,
    retrieved: true,
    sources: grounded.map(g => g.chunk.pageUrl),
    usedTools: toolResults.map(t => t.tool),
    grounded,
  };
}

/**
 * Synchronous variant of answerQuery for synchronous pipelines
 */
export function answerQuerySync({
  botId = 'default',
  bot = {},
  message = '',
  store,
  embedFn = embedTextsSync,
  composeFn = null,
}) {
  const queryEmbedding = embedFn([message])[0];
  const retrieved = store.search(botId, queryEmbedding, { topK: TOP_K, rawQuery: message });
  const grounded = retrieved.filter(r => r.score >= RELEVANCE_THRESHOLD);

  if (grounded.length === 0) {
    return buildFallback({ bot, message, capabilities: bot.capabilities });
  }

  const reply = composeFn
    ? composeFn({ message, chunks: grounded.map(g => ({ text: g.chunk.text, url: g.chunk.pageUrl, score: g.score })), toolResults: [] })
    : grounded.map(g => g.chunk.text).join('\n\n');

  return {
    reply,
    sources: grounded.map(g => g.chunk.pageUrl),
    usedTools: [],
    grounded,
  };
}

function looksLikeProductQuery(message) {
  // Cheap pre-filter before spending a tool call; the real judgment of
  // "is this actually a product" still lives in the tool's own retrieval,
  // not in a hand-maintained keyword list like this one -- this only
  // decides whether it's worth trying at all.
  return /\b(buy|want|need|looking for|do you have|sell|stock)\b/i.test(message) || message.split(' ').length <= 6;
}

function buildFallback({ bot, message, capabilities }) {
  const companyName = bot?.company?.name || 'us';
  const searchUrl = capabilities?.catalogBrowsing?.enabled
    ? `${bot?.company?.websiteUrl || ''}/search?q=${encodeURIComponent(message)}`
    : null;

  const quickReplies = [];
  if (searchUrl) {
    quickReplies.push({ label: `🔍 Search "${truncate(message, 20)}"`, url: searchUrl });
  }
  quickReplies.push({ label: 'Talk to the team', payload: `I want to speak with someone from the ${companyName} team` });

  return {
    reply: searchUrl
      ? `I don't have that in my indexed knowledge yet, but you can search ${companyName}'s live catalog directly:`
      : `I don't have specific information on that yet. Let me connect you with the ${companyName} team so you get an accurate answer.`,
    retrieved: false,
    sources: [],
    usedTools: [],
    quickReplies,
  };
}

function truncate(s, n) { return s.length > n ? s.slice(0, n - 1) + '…' : s; }
