/**
 * retrieve-and-respond.js
 * ----------------------------------------------------------------------------
 * Turns ingested Pages (from ingest.js) into a searchable knowledge store and
 * answers user queries from it, with a single hard relevance floor instead of
 * the growing pile of hand-written keyword/category gates this replaces.
 *
 * Design rules this file enforces:
 *   1. One RELEVANCE_THRESHOLD, used everywhere. No content-type gets a
 *      different bar. If nothing clears it, there is no retrieval answer --
 *      full stop, regardless of how confident-sounding a low-score chunk is.
 *   2. Tools (product search, booking, etc.) are only offered to the model
 *      if the bot's capabilities say they're evidence-backed (see ingest.js).
 *      A bot literally cannot call a tool that isn't in its own list.
 *   3. Checkout / payment instructions are generated by ONE function
 *      (buildCheckoutInstructions) which refuses unless a verified payment
 *      credential is attached to the bot. Nothing else in this file, or in
 *      the LLM's free text, is allowed to emit payment instructions --
 *      the model is only ever given retrieved facts and tool results to
 *      compose from, never asked to invent a payment flow.
 *   4. Every answer either cites a source chunk/tool result or says plainly
 *      it doesn't know. There is no "confident guess" path.
 * ----------------------------------------------------------------------------
 */

// ---------------------------------------------------------------------------
// Config
// ---------------------------------------------------------------------------

export const RELEVANCE_THRESHOLD = 0.45; // cosine similarity, 0..1. Calibrate from logged (query, score, was_correct) data.
const TOP_K = 6;

// ---------------------------------------------------------------------------
// Built-in Default Embedding Vectorizer (Zero Dependency, Dependency Injected)
// ---------------------------------------------------------------------------

const EMBED_DIM = 2048;
const STOP_WORDS = new Set([
  'the', 'a', 'an', 'is', 'are', 'was', 'were', 'be', 'been', 'being',
  'of', 'for', 'in', 'on', 'at', 'to', 'from', 'by', 'with', 'about',
  'do', 'does', 'did', 'you', 'we', 'i', 'me', 'my', 'our', 'it', 'its',
  'and', 'or', 'but', 'if', 'so', 'as', 'into', 'than', 'then',
  'what', 'which', 'who', 'whom', 'whose', 'where', 'when', 'why', 'how',
  'can', 'could', 'would', 'should',
  'much', 'many', 'also', 'just',
  'http', 'https', 'www', 'com', 'org', 'net', 'co', 'ke', 'io', 'ai', 'html', 'htm', 'php', 'aspx', 'catalog'
]);

/**
 * Deterministic bag-of-stems embedding vectorizer.
 * Provides high-precision lexical & morphological cosine similarity offline.
 * Can be swapped via dependency injection with OpenAI / Gemini / Ollama embeddings.
 *
 * @param {string[]} texts
 * @returns {number[][]}
 */
export function embedTextsSync(texts) {
  return texts.map(text => {
    let clean = (text || '').trim();
    const urlMatch = clean.match(/[?&]q=([^&#]+)/i);
    if (urlMatch) {
      try { clean = decodeURIComponent(urlMatch[1].replace(/\+/g, ' ')).trim(); } catch(e) {}
    } else if (/^https?:\/\//i.test(clean)) {
      try {
        const p = new URL(clean).pathname.split('/').filter(Boolean);
        if (p.length) clean = p[p.length - 1].replace(/[-_]+/g, ' ').trim();
      } catch(e) {}
    }

    const vec = new Float64Array(EMBED_DIM);
    const words = clean
      .toLowerCase()
      .replace(/[^\w\s]/g, ' ')
      .split(/\s+/)
      .filter(w => w.length > 1 && !STOP_WORDS.has(w));

    if (words.length === 0) return Array.from(vec);

    for (let i = 0; i < words.length; i++) {
      const word = words[i];
      const stem = word.replace(/(ing|tions?|tionals?|ated|ates?|ating|ed|es|s|ments?|ables?|ity|al|ive|izes?|ises?)$/, '');
      
      // Hash unigram/stem
      let h1 = 5381;
      for (let j = 0; j < stem.length; j++) h1 = ((h1 << 5) + h1) ^ stem.charCodeAt(j);
      vec[Math.abs(h1) % EMBED_DIM] += 1.0;

      // Bigram with next stem
      if (i < words.length - 1) {
        const nextStem = words[i + 1].replace(/(ing|tions?|tionals?|ated|ates?|ating|ed|es|s|ments?|ables?|ity|al|ive|izes?|ises?)$/, '');
        const bigram = stem + '_' + nextStem;
        let h2 = 5381;
        for (let j = 0; j < bigram.length; j++) h2 = ((h2 << 5) + h2) ^ bigram.charCodeAt(j);
        vec[Math.abs(h2) % EMBED_DIM] += 1.2;
      }
    }

    // Sublinear length normalization to avoid penalizing comprehensive knowledge chunks
    let norm = 0;
    for (let i = 0; i < EMBED_DIM; i++) norm += vec[i] * vec[i];
    norm = Math.pow(norm, 0.25);
    if (norm > 0) {
      for (let i = 0; i < EMBED_DIM; i++) vec[i] /= norm;
    }

    return Array.from(vec);
  });
}

export async function defaultEmbedFn(texts) {
  return embedTextsSync(texts);
}

/**
 * Default prose composer from grounded facts and tool results.
 * Strictly never hallucinates pricing, stock, or payment info.
 */
export async function defaultComposeFn({ message, chunks, toolResults }) {
  if (toolResults && toolResults.length > 0) {
    const prodTool = toolResults.find(t => t.tool === 'search_products');
    if (prodTool && prodTool.results && prodTool.results.length > 0) {
      const items = prodTool.results
        .map(p => `• **${p.name}**${p.price != null ? ' — ' + (p.currency || 'KES') + ' ' + Number(p.price).toLocaleString() : ''}`)
        .join('\n');
      return `Here are the matching items from our catalog:\n\n${items}`;
    }
  }
  if (chunks && chunks.length > 0) {
    return chunks.map(c => c.text).join('\n\n');
  }
  return '';
}

