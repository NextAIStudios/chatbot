/**
 * @param {import('./ingest.js').Page[]} pages
 * @param {number} [maxTokensPerChunk=400]
 * @returns {{id:string, pageUrl:string, pageTitle:string, contentType:string, text:string, structuredData:any}[]}
 */
export function chunkPages(pages, maxTokensPerChunk = 400) {
  const chunks = [];
  for (const page of pages) {
    const words = page.text.split(/\s+/);
    const approxWordsPerChunk = Math.max(10, Math.floor(maxTokensPerChunk * 0.75)); // rough token->word ratio
    for (let i = 0; i < words.length; i += approxWordsPerChunk) {
      const slice = words.slice(i, i + approxWordsPerChunk).join(' ');
      if (slice.trim().length < 20) continue;
      chunks.push({
        id: `${page.url}#${i}`,
        pageUrl: page.url,
        pageTitle: page.title,
        contentType: page.contentType,
        text: slice,
        structuredData: page.structuredData || null,
      });
    }
  }
  return chunks;
}

/**
 * In-memory vector store, one instance per bot. Swap for pgvector/OpenSearch
 * in production -- the interface (upsert/search) is what matters.
 */
export class KnowledgeStore {
  constructor() {
    /** @type {Map<string, {chunk: object, embedding: number[]}>} */
    this.byBot = new Map();
  }

  /**
   * Synchronous upsert using synchronous embedding vectorizer
   */
  upsertSync(botId, chunks, embedSync = embedTextsSync) {
    const embeddings = embedSync(chunks.map(c => c.text));
    const entries = chunks.map((chunk, i) => ({ chunk, embedding: embeddings[i] }));
    this.byBot.set(botId, entries);
  }

  /**
   * @param {string} botId
   * @param {object[]} chunks
   * @param {(texts: string[]) => Promise<number[][]>} [embedFn=defaultEmbedFn]
   */
  async upsert(botId, chunks, embedFn = defaultEmbedFn) {
    const embeddings = await embedFn(chunks.map(c => c.text));
    const entries = chunks.map((chunk, i) => ({ chunk, embedding: embeddings[i] }));
    this.byBot.set(botId, entries);
  }

  /**
   * @param {string} botId
   * @param {number[]} queryEmbedding
   * @param {{topK?:number, contentTypeFilter?:string[], rawQuery?:string}} [opts]
   * @returns {{chunk:object, score:number}[]}  sorted desc by score
   */
  search(botId, queryEmbedding, opts = {}) {
    const entries = this.byBot.get(botId) || [];
    const filtered = opts.contentTypeFilter
      ? entries.filter(e =>
          opts.contentTypeFilter.includes(e.chunk.contentType) ||
          (e.chunk.category && opts.contentTypeFilter.includes(e.chunk.category))
        )
      : entries;

    return filtered
      .map(e => {
        let score = cosineSimilarity(queryEmbedding, e.embedding);
        if (opts.rawQuery) {
          const kwStr = (e.chunk.kbItem && e.chunk.kbItem.keywords)
            ? (Array.isArray(e.chunk.kbItem.keywords) ? e.chunk.kbItem.keywords.join(' ') : String(e.chunk.kbItem.keywords))
            : '';
          const overlap = computeLexicalCoverage(opts.rawQuery, e.chunk.pageTitle || '', kwStr, e.chunk.text || '');
          score = Math.max(score, overlap);
        }
        if (e.chunk.kbItem && e.chunk.kbItem.isCustomTrained) {
          score = Math.min(1.0, score * 1.35);
        }
        return { chunk: e.chunk, score };
      })
      .sort((a, b) => b.score - a.score)
      .slice(0, opts.topK || TOP_K);
  }
}

function computeLexicalCoverage(queryText, docTitle, docKeywords, docText) {
  let cleanQuery = (queryText || '').trim();
  const urlMatch = cleanQuery.match(/[?&]q=([^&#]+)/i);
  if (urlMatch) {
    try { cleanQuery = decodeURIComponent(urlMatch[1].replace(/\+/g, ' ')).trim(); } catch(e) {}
  } else if (/^https?:\/\//i.test(cleanQuery)) {
    try {
      const p = new URL(cleanQuery).pathname.split('/').filter(Boolean);
      if (p.length) cleanQuery = p[p.length - 1].replace(/[-_]+/g, ' ').trim();
    } catch(e) {}
  }

  const normQuery = cleanQuery.toLowerCase().replace(/[^\w\s]/g, ' ').replace(/\s+/g, ' ').trim();
  const normTitle = (docTitle || '').toLowerCase().replace(/[^\w\s]/g, ' ').replace(/\s+/g, ' ').trim();
  if (normTitle && normQuery && (normTitle === normQuery || normTitle.includes(normQuery) || normQuery.includes(normTitle))) {
    return 1.0;
  }

  const STOP = new Set([
    'the', 'a', 'an', 'is', 'are', 'was', 'were', 'be', 'been', 'am',
    'in', 'on', 'at', 'to', 'for', 'of', 'by', 'with', 'from',
    'do', 'does', 'did', 'i', 'me', 'my', 'we', 'our', 'you', 'your',
    'want', 'need', 'would', 'like', 'have', 'can', 'could', 'should',
    'what', 'which', 'who', 'whom', 'whose', 'where', 'when', 'why', 'how',
    'tell', 'about', 'and', 'or', 'any', 'some', 'there', 'please',
    'looking', 'look', 'find', 'show', 'give', 'get', 'much', 'many', 'also', 'just', 'search'
  ]);
  let qWords = cleanQuery.toLowerCase().replace(/[^\w\s]/g, ' ').split(/\s+/).filter(w => w.length > 2 && !STOP.has(w));
  if (qWords.length === 0) {
    const MINIMAL_STOP = new Set(['the', 'a', 'an', 'is', 'are', 'was', 'were', 'it', 'in', 'on', 'at', 'to', 'for', 'of', 'by']);
    qWords = cleanQuery.toLowerCase().replace(/[^\w\s]/g, ' ').split(/\s+/).filter(w => w.length > 1 && !MINIMAL_STOP.has(w));
  }
  const docLower = (docText || '').toLowerCase();
  const titleLower = (docTitle || '').toLowerCase();
  const kwLower = (docKeywords || '').toLowerCase();
  if (qWords.length === 0) return 0;
  let overlap = 0;
  for (const qw of qWords) {
    const stem = qw.replace(/(ing|tions?|tionals?|ated|ates?|ating|ed|es|s)$/, '');
    if (titleLower.includes(qw) || kwLower.includes(qw) || (stem.length >= 3 && (titleLower.includes(stem) || kwLower.includes(stem)))) {
      overlap += 1.0;
    } else if (docLower.includes(qw) || (stem.length >= 3 && docLower.includes(stem))) {
      overlap += 0.5;
    }
  }
  return Math.min(1.0, (overlap / qWords.length) * 0.85);
}

function cosineSimilarity(a, b) {
  if (!a || !b || a.length !== b.length) return 0;
  let dot = 0, na = 0, nb = 0;
  for (let i = 0; i < a.length; i++) { dot += a[i] * b[i]; na += a[i] ** 2; nb += b[i] ** 2; }
  if (na === 0 || nb === 0) return 0;
  return Math.min(1.0, dot / (Math.sqrt(na) * Math.sqrt(nb)));
}

